/* Host unit tests for the Seplos protocol component. Build with test/host/run_tests.sh */
#include "seplos_proto.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int failures;
static int checks;

#define CHECK(cond)                                                                 \
    do {                                                                            \
        checks++;                                                                   \
        if (!(cond)) {                                                              \
            failures++;                                                             \
            fprintf(stderr, "%s:%d: CHECK failed: %s\n", __FILE__, __LINE__, #cond); \
        }                                                                           \
    } while (0)

#define CHECK_EQ(a, b)                                                                     \
    do {                                                                                   \
        checks++;                                                                          \
        long long _a = (long long)(a), _b = (long long)(b);                                \
        if (_a != _b) {                                                                    \
            failures++;                                                                    \
            fprintf(stderr, "%s:%d: %s == %s failed (%lld != %lld)\n", __FILE__, __LINE__, \
                    #a, #b, _a, _b);                                                       \
        }                                                                                  \
    } while (0)

/* Generated by tools/seplos_frames.py (independent Python encoder). */
static const char TELEMETRY_FRAME[] =
    "~2000460010960000100D080D070D090D0A0D0D0D050D0A0D090D0D0D090D0D0D0C0D0C0D0B0D0C0D09060B8A0B890B840B86"
    "0BB50B99FF4514DD4C050A4E2003CD4E20005603E814E20000000000000000DD4D\r";

static const char ALARM_FRAME[] =
    "~20004600505600001000000000000000000000000000000000060000000000000000000001000000040320000100000000ED72\r";

static void test_request_frames_match_original_firmware(void)
{
    char buf[64];
    /* These two strings are hard-coded in the original ESP8266 firmware v1.0.1.2. */
    CHECK_EQ(seplos_build_telemetry_request(buf, sizeof buf, 0), 20);
    CHECK(strcmp(buf, "~20004642E00200FD37\r") == 0);
    CHECK_EQ(seplos_build_shutdown_request(buf, sizeof buf, 0), 24);
    CHECK(strcmp(buf, "~20004645A006000400FC70\r") == 0);

    /* Other addresses must produce self-consistent frames. */
    for (int addr = 0; addr < 16; addr++) {
        seplos_frame_t f;
        CHECK(seplos_build_telemetry_request(buf, sizeof buf, (uint8_t)addr) > 0);
        CHECK_EQ(seplos_parse_frame(buf, strlen(buf), &f), SEPLOS_ERR_RTN); /* CID2 0x42 sits in RTN slot */
        CHECK_EQ(f.addr, addr);
        CHECK_EQ(f.rtn, 0x42);
        CHECK_EQ(f.info_len, 1);
        CHECK_EQ(f.info[0], addr);
        CHECK(seplos_build_alarm_request(buf, sizeof buf, (uint8_t)addr) > 0);
        CHECK_EQ(seplos_parse_frame(buf, strlen(buf), &f), SEPLOS_ERR_RTN);
        CHECK_EQ(f.rtn, 0x44);
    }

    /* Buffer too small -> 0, no overflow. */
    CHECK_EQ(seplos_build_telemetry_request(buf, 20, 0), 0);
    CHECK_EQ(seplos_build_telemetry_request(buf, 21, 0), 20);
}

static void test_length_field(void)
{
    CHECK_EQ(seplos_length_field(0x002), 0xE002);
    CHECK_EQ(seplos_length_field(0x006), 0xA006);
    CHECK_EQ(seplos_length_field(0x096), 0x1096);
    CHECK_EQ(seplos_length_field(0x000), 0x0000);
}

static void test_decode_telemetry(void)
{
    seplos_frame_t f;
    seplos_telemetry_t t;
    CHECK_EQ(seplos_parse_frame(TELEMETRY_FRAME, strlen(TELEMETRY_FRAME), &f), SEPLOS_OK);
    CHECK_EQ(f.addr, 0);
    CHECK_EQ(f.cid1, 0x46);
    CHECK_EQ(f.info_len, 75);
    CHECK_EQ(seplos_decode_telemetry(&f, &t), SEPLOS_OK);
    CHECK_EQ(t.cell_count, 16);
    CHECK_EQ(t.cell_mv[0], 3336);
    CHECK_EQ(t.cell_mv[15], 3337);
    CHECK_EQ(t.cell_min_mv, 3333);
    CHECK_EQ(t.cell_min_idx, 5);  /* Cell6, as shown in the original UI */
    CHECK_EQ(t.cell_max_mv, 3341);
    CHECK_EQ(t.cell_max_idx, 4);  /* Cell5: first cell reaching the max */
    CHECK_EQ(t.cell_diff_mv, 8);
    CHECK_EQ(t.temp_count, 6);
    CHECK_EQ(t.temp_dc[0], 223);
    CHECK_EQ(t.temp_dc[4], 266);
    CHECK_EQ(t.temp_dc[5], 238);
    CHECK_EQ(t.current_ca, -187);
    CHECK_EQ(t.voltage_cv, 5341);
    CHECK_EQ(t.remain_cah, 19461);
    CHECK_EQ(t.custom_count, 10);
    CHECK_EQ(t.capacity_cah, 20000);
    CHECK_EQ(t.soc_pm, 973);
    CHECK_EQ(t.rated_cah, 20000);
    CHECK_EQ(t.cycles, 86);
    CHECK_EQ(t.soh_pm, 1000);
    CHECK_EQ(t.port_voltage_cv, 5346);
}

static void test_decode_alarms(void)
{
    seplos_frame_t f;
    seplos_alarms_t a;
    CHECK_EQ(seplos_parse_frame(ALARM_FRAME, strlen(ALARM_FRAME), &f), SEPLOS_OK);
    CHECK_EQ(seplos_decode_alarms(&f, &a), SEPLOS_OK);
    CHECK_EQ(a.cell_count, 16);
    CHECK_EQ(a.temp_count, 6);
    CHECK_EQ(a.event[1], 0x01);
    CHECK_EQ(a.event[5], 0x04);
    CHECK_EQ(a.switch_state, 0x03);
    CHECK_EQ(a.balancing, 0x0020);
    CHECK_EQ(a.system_state, 0x01);
    CHECK_EQ(seplos_alarm_count(&a), 2);
    CHECK(strcmp(seplos_alarm_event_text(1, 0), "Cell high voltage alarm") == 0);
    CHECK(strcmp(seplos_alarm_event_text(5, 2), "Residual capacity alarm") == 0);
    CHECK(seplos_alarm_event_text(3, 7) == NULL);
    CHECK(seplos_alarm_event_is_protection(1, 1));
    CHECK(!seplos_alarm_event_is_protection(1, 0));
}

static void test_rejects_corrupt_frames(void)
{
    char buf[sizeof TELEMETRY_FRAME];
    seplos_frame_t f;
    size_t n = strlen(TELEMETRY_FRAME);

    CHECK_EQ(seplos_parse_frame("", 0, &f), SEPLOS_ERR_NO_DATA);
    CHECK_EQ(seplos_parse_frame("garbage", 7, &f), SEPLOS_ERR_SOI);
    CHECK_EQ(seplos_parse_frame("~2000", 5, &f), SEPLOS_ERR_TOO_SHORT);

    /* checksum */
    memcpy(buf, TELEMETRY_FRAME, n + 1);
    buf[20] = buf[20] == '0' ? '1' : '0';
    CHECK_EQ(seplos_parse_frame(buf, n, &f), SEPLOS_ERR_CHECKSUM);

    /* length checksum nibble */
    memcpy(buf, TELEMETRY_FRAME, n + 1);
    buf[9] = '2';
    CHECK_EQ(seplos_parse_frame(buf, n, &f), SEPLOS_ERR_LENGTH_CHECKSUM);

    /* missing CR */
    memcpy(buf, TELEMETRY_FRAME, n + 1);
    buf[n - 1] = 'X';
    CHECK_EQ(seplos_parse_frame(buf, n, &f), SEPLOS_ERR_EOI);

    /* truncated */
    CHECK_EQ(seplos_parse_frame(TELEMETRY_FRAME, n - 3, &f), SEPLOS_ERR_TOO_SHORT);

    /* non hex */
    memcpy(buf, TELEMETRY_FRAME, n + 1);
    buf[30] = 'G';
    CHECK(seplos_parse_frame(buf, n, &f) != SEPLOS_OK);

    /* leading noise is skipped */
    char noisy[sizeof TELEMETRY_FRAME + 4] = "\x00\xff\r";
    memcpy(noisy + 3, TELEMETRY_FRAME, n + 1);
    CHECK_EQ(seplos_parse_frame(noisy, n + 3, &f), SEPLOS_OK);

    /* The checksum covers the ASCII characters, so a lower-cased copy must be rejected. */
    for (size_t i = 0; i < n; i++) {
        buf[i] = (TELEMETRY_FRAME[i] >= 'A' && TELEMETRY_FRAME[i] <= 'F') ? (char)(TELEMETRY_FRAME[i] + 32) : TELEMETRY_FRAME[i];
    }
    CHECK_EQ(seplos_parse_frame(buf, n, &f), SEPLOS_ERR_CHECKSUM);
}

static void test_short_payload(void)
{
    /* Valid frame whose INFO claims 16 cells but stops early. */
    uint8_t info[10] = { 0x00, 0x00, 0x10, 0x0D, 0x08 };
    char buf[128];
    seplos_frame_t f;
    seplos_telemetry_t t;
    seplos_alarms_t a;
    CHECK(seplos_build_frame(buf, sizeof buf, 0, 0x46, 0x00, info, sizeof info) > 0);
    CHECK_EQ(seplos_parse_frame(buf, strlen(buf), &f), SEPLOS_OK);
    CHECK_EQ(seplos_decode_telemetry(&f, &t), SEPLOS_ERR_PAYLOAD);
    CHECK_EQ(seplos_decode_alarms(&f, &a), SEPLOS_ERR_PAYLOAD);

    /* Too many cells declared */
    uint8_t info2[4] = { 0x00, 0x00, 0xFF, 0x00 };
    CHECK(seplos_build_frame(buf, sizeof buf, 0, 0x46, 0x00, info2, sizeof info2) > 0);
    CHECK_EQ(seplos_parse_frame(buf, strlen(buf), &f), SEPLOS_OK);
    CHECK_EQ(seplos_decode_telemetry(&f, &t), SEPLOS_ERR_PAYLOAD);
}

static void test_cell_count_not_16(void)
{
    /* The original firmware hard-coded the temperature offset for 16 cells.
     * Build an 8-cell frame and make sure temperatures still decode. */
    uint8_t info[128];
    size_t p = 0;
    info[p++] = 0; info[p++] = 0; info[p++] = 8;
    for (int i = 0; i < 8; i++) { info[p++] = 0x0C; info[p++] = (uint8_t)(0xE4 + i); }
    info[p++] = 2;
    info[p++] = 0x0B; info[p++] = 0xB5; /* 2997 -> 26.6 C */
    info[p++] = 0x0A; info[p++] = 0xAB; /* 2731 -> 0.0 C */
    info[p++] = 0x01; info[p++] = 0xF4; /* +5.00 A */
    info[p++] = 0x0A; info[p++] = 0x28; /* 26.00 V */
    info[p++] = 0x13; info[p++] = 0x88; /* 50.00 Ah */
    info[p++] = 10;
    info[p++] = 0x27; info[p++] = 0x10; /* 100.00 Ah */
    info[p++] = 0x01; info[p++] = 0xF4; /* 50.0 % */
    info[p++] = 0x27; info[p++] = 0x10;
    info[p++] = 0x00; info[p++] = 0x07;
    info[p++] = 0x03; info[p++] = 0xDE; /* 99.0 % */
    info[p++] = 0x0A; info[p++] = 0x28;
    char buf[300];
    seplos_frame_t f;
    seplos_telemetry_t t;
    CHECK(seplos_build_frame(buf, sizeof buf, 3, 0x46, 0x00, info, p) > 0);
    CHECK_EQ(seplos_parse_frame(buf, strlen(buf), &f), SEPLOS_OK);
    CHECK_EQ(f.addr, 3);
    CHECK_EQ(seplos_decode_telemetry(&f, &t), SEPLOS_OK);
    CHECK_EQ(t.cell_count, 8);
    CHECK_EQ(t.cell_min_mv, 0x0CE4);
    CHECK_EQ(t.cell_max_idx, 7);
    CHECK_EQ(t.temp_count, 2);
    CHECK_EQ(t.temp_dc[0], 266);
    CHECK_EQ(t.temp_dc[1], 0);
    CHECK_EQ(t.current_ca, 500);
    CHECK_EQ(t.soc_pm, 500);
    CHECK_EQ(t.cycles, 7);
    CHECK_EQ(t.soh_pm, 990);
    CHECK_EQ(t.reserved[0], 0); /* absent -> zero */
}

static void test_rtn_error(void)
{
    char buf[64];
    seplos_frame_t f;
    /* RTN 0x04 (CID2 invalid) with empty INFO */
    CHECK(seplos_build_frame(buf, sizeof buf, 0, 0x46, 0x04, NULL, 0) > 0);
    CHECK_EQ(seplos_parse_frame(buf, strlen(buf), &f), SEPLOS_ERR_RTN);
    CHECK_EQ(f.rtn, 4);
}

static uint32_t rng = 0x12345678;
static uint32_t xorshift(void)
{
    rng ^= rng << 13;
    rng ^= rng >> 17;
    rng ^= rng << 5;
    return rng;
}

static void test_fuzz(void)
{
    /* Random mutations / truncations must never crash or read out of bounds
     * (run under ASan/UBSan). */
    char buf[SEPLOS_MAX_FRAME_CHARS + 8];
    size_t n = strlen(TELEMETRY_FRAME);
    seplos_frame_t f;
    seplos_telemetry_t t;
    seplos_alarms_t a;
    for (int iter = 0; iter < 200000; iter++) {
        memcpy(buf, TELEMETRY_FRAME, n);
        size_t len = n;
        int muts = (int)(xorshift() % 4);
        for (int m = 0; m < muts; m++) {
            buf[xorshift() % n] = (char)(xorshift() & 0xFF);
        }
        if (xorshift() % 3 == 0) {
            len = xorshift() % (n + 1);
        }
        /* heap copy of exact length so ASan catches over-reads */
        char *heap = malloc(len ? len : 1);
        memcpy(heap, buf, len);
        if (seplos_parse_frame(heap, len, &f) == SEPLOS_OK) {
            (void)seplos_decode_telemetry(&f, &t);
            (void)seplos_decode_alarms(&f, &a);
            (void)seplos_alarm_count(&a);
        }
        free(heap);
    }
    /* Fully random INFO bytes through the decoders. */
    for (int iter = 0; iter < 50000; iter++) {
        memset(&f, 0, sizeof f);
        f.info_len = (uint16_t)(xorshift() % (SEPLOS_MAX_INFO_BYTES + 1));
        for (int i = 0; i < f.info_len; i++) {
            f.info[i] = (uint8_t)xorshift();
        }
        (void)seplos_decode_telemetry(&f, &t);
        (void)seplos_decode_alarms(&f, &a);
        (void)seplos_alarm_count(&a);
    }
    checks++;
}

int main(void)
{
    test_request_frames_match_original_firmware();
    test_length_field();
    test_decode_telemetry();
    test_decode_alarms();
    test_rejects_corrupt_frames();
    test_short_payload();
    test_cell_count_not_16();
    test_rtn_error();
    test_fuzz();
    printf("%d checks, %d failures\n", checks, failures);
    return failures ? 1 : 0;
}
